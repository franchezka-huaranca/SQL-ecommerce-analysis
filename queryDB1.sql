use classicmodels;
select p.productLine,
    sum(od.quantityOrdered) as totalQuantityOrdered,
    sum(od.quantityOrdered * od.priceEach) as totalLineRevenue,
    (sum(od.quantityOrdered * od.priceEach) / SUM(od.quantityOrdered)) as averagePricePerUnit
from products p
join orderDetails od on p.productCode = od.productCode
group by p.productLine
having SUM(od.quantityOrdered) > (
        select AVG(sub.totalOrdered)
        from
            (
                select SUM(od_sub.quantityOrdered) AS totalOrdered
                from orderDetails od_sub
                join products p_sub ON od_sub.productCode = p_sub.productCode
                group by p_sub.productLine
            ) as sub
    )
    and (SUM(od.quantityOrdered * od.priceEach) / SUM(od.quantityOrdered)) < (
        select AVG(od_avg.priceEach)
        from orderDetails od_avg
    )
order by averagePricePerUnit ASC;

/*Business value of the query: The product line on this query finds product lines that have a very high volume of items ordered but 
generate a lower than average revenue per order line. This suggests a need to review pricing strategies, reduce costs, or investigate 
potential heavy discounting in that product line.*/