/* Joint Sub-Query 14*/
select c.customerName, o.orderNumber, (
	select sum(od.quantityOrdered * od.priceEach)
    from orderdetails od
		where od.orderNumber = o.orderNumber) AS TotalOrderValue
	from customers c
    join orders o 
    on c.customerNumber = o.customerNumber
		where (
        select SUM(od.quantityOrdered * od.priceEach)
        from orderdetails od
			where od.orderNumber = o.orderNumber) > (
			/*Subquery to calculate the average total order value across all orders*/
			select AVG(OrderTotal)
            from (
            select SUM(quantityOrdered * priceEach) as OrderTotal
            from orderdetails
            group by orderNumber) as SubTotals
    )
order by TotalOrderValue DESC;

/*Business value of the query: This query helps identify high-value orders and the customers associated with them, 
which is useful for negotiating with this customers, as they have a high power of negotiation.*/

